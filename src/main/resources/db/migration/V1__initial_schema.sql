-- Bảng admin_accounts
CREATE TABLE IF NOT EXISTS admin_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    hashed_password VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    account_role VARCHAR(50) NOT NULL CHECK (account_role IN ('SYSTEM', 'CAMPAIGN_MANAGER', 'SECURITY_MANAGER', 'FINANCE_MANAGER'))
);

-- Bảng campaigns
CREATE TABLE IF NOT EXISTS campaigns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_name VARCHAR(255) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'ENDED', 'PAUSED')),
    admin_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_campaign_admin FOREIGN KEY (admin_id) REFERENCES admin_accounts(id)
);

-- Bảng rewards
CREATE TABLE IF NOT EXISTS rewards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward_name VARCHAR(255) NOT NULL,
    condition_type VARCHAR(50) NOT NULL CHECK (condition_type IN ('MIN_CART_AMOUNT', 'TIME_WINDOW', 'CUSTOMER_SEGMENT', 'COMPOSITE')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED')),
    reward_config_json JSONB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Bảng conditions
CREATE TABLE IF NOT EXISTS conditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condition_name VARCHAR(255) NOT NULL,
    reward_type VARCHAR(50) NOT NULL CHECK (reward_type IN ('PERCENTAGE', 'FIXED', 'BUY_X_GET_Y', 'TIERED_PERCENTAGE')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED')),
    condition_config_json JSONB NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Bảng batch_rules
CREATE TABLE IF NOT EXISTS batch_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward_id BIGINT NOT NULL,
    condition_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_batch_rule_reward FOREIGN KEY (reward_id) REFERENCES rewards(id),
    CONSTRAINT fk_batch_rule_condition FOREIGN KEY (condition_id) REFERENCES conditions(id)
);

-- Bảng voucher_batches
CREATE TABLE IF NOT EXISTS voucher_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id BIGINT NOT NULL,
    rule_id BIGINT NOT NULL,
    batch_type VARCHAR(50) NOT NULL CHECK (batch_type IN ('GENERIC', 'BULK')),
    code_config_json JSONB NOT NULL,
    duration_unit VARCHAR(50) NOT NULL CHECK (duration_unit IN ('SECONDS', 'MINUTES', 'HOURS', 'DAYS')),
    duration_value INT NOT NULL,
    generated_count INT NOT NULL DEFAULT 0,
    redeemed_count INT NOT NULL DEFAULT 0,
    distribution_channels_json JSONB NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('DRAFT', 'GENERATED')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_voucher_batch_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns(id),
    CONSTRAINT fk_voucher_batch_rule FOREIGN KEY (rule_id) REFERENCES batch_rules(id)
);

-- Bảng vouchers
CREATE TABLE IF NOT EXISTS vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    campaign_id BIGINT NOT NULL,
    code VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_voucher_batch FOREIGN KEY (batch_id) REFERENCES voucher_batches(id),
    CONSTRAINT fk_voucher_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns(id)
);

-- Bảng distribution_logs
CREATE TABLE IF NOT EXISTS distribution_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL,
    campaign_id BIGINT NOT NULL,
    channel VARCHAR(50) NOT NULL CHECK (channel IN ('EMAIL', 'WEBHOOK')),
    target_address VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    sent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_distribution_log_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id),
    CONSTRAINT fk_distribution_log_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns(id)
);

-- Bảng redemption_logs
CREATE TABLE IF NOT EXISTS redemption_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL,
    customer_id VARCHAR(50) NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    device_fingerprint VARCHAR(255) NOT NULL,
    original_amount NUMERIC(15,2) NOT NULL,
    discount_amount NUMERIC(15,2) NOT NULL,
    final_amount NUMERIC(15,2) NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('SUCCESS', 'FAILED')),
    failure_reason VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_redemption_log_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id)
);

-- Bảng fraud_logs
CREATE TABLE IF NOT EXISTS fraud_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id BIGINT NOT NULL,
    customer_id VARCHAR(50) NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    device_fingerprint VARCHAR(255) NOT NULL,
    violation_rule VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_fraud_log_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id)
);

-- Bảng customer_vouchers
CREATE TABLE IF NOT EXISTS customer_vouchers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(50) NOT NULL,
    voucher_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL CHECK (status IN ('AVAILABLE', 'UNAVAILABLE', 'USED', 'EXPIRED')),
    claimed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expired_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_customer_voucher_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id)
);

-- Bảng rate_limit_configs
CREATE TABLE IF NOT EXISTS rate_limit_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_limit_config_name VARCHAR(255) NOT NULL,
    endpoint_pattern VARCHAR(255) NOT NULL,
    limit_scope VARCHAR(50) NOT NULL CHECK (limit_scope IN ('CUSTOMER_ID', 'DEVICE_FINGERPRINT', 'IP')),
    max_request INT NOT NULL,
    time_window_seconds INT NOT NULL,
    action_on_exceed VARCHAR(50) NOT NULL CHECK (action_on_exceed IN ('REJECT_429', 'BLACKLIST')),
    priority INT NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Bảng black_lists
CREATE TABLE IF NOT EXISTS black_lists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blacklist_type VARCHAR(50) NOT NULL CHECK (blacklist_type IN ('CUSTOMER', 'DEVICE_FINGERPRINT', 'IP')),
    target_value VARCHAR(255) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expired_at TIMESTAMP
);